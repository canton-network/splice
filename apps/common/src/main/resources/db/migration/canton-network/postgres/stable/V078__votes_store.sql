-- Historical vote results, i.e., the result of exercised DsoRules_CloseVoteRequest choices.
create table votes_store_results
(
    -- Generated row id, only used as an opaque pagination token in the API.
    -- Do not use for ordering results: due to backfilling, rows in this table
    -- may not be inserted in record time order, and their order may differ across SVs.
    row_id              bigint generated by default as identity,

    -- The id of the TxLog store of the app's ACS store, which this table is ingested together with.
    store_id            int     not null,

    -- Data identifying the transaction tree in which the exercise choice was executed.
    record_time         bigint  not null,
    synchronizer_id     text    not null,
    update_id           text    not null,

    -- Event number of the exercise choice within the transaction tree.
    -- To make sure this field is identical across SVs, the event number
    -- is assigned by in-order traversing the DSO-visible part of the transaction tree.
    event_number        int     not null,

    -- Data extracted from the choice result.
    vote_action_name    text    not null,
    vote_requester_name text    not null,
    vote_accepted       boolean not null,
    vote_tracking_cid   text    not null,
    vote_completed_at   bigint,
    vote_effective_at   bigint,

    -- Full result of the exercise choice, encoded in protobuf-json format.
    choice_result       jsonb   not null,

    -- Set if the choice result could not be decoded, e.g., because of an incompatibility with a newer Daml model.
    -- In that case the row is a placeholder: it keeps the data that identifies the vote (record time, event number,
    -- update id, synchronizer id), and the other columns hold placeholder values.
    -- This is not expected to happen in practice, see DbVotesStore.
    error               text,

    -- Primary key identifies the DsoRules_CloseVoteRequest exercise choice,
    -- and is used for paginating backfilling requests.
    constraint votes_store_results_id_pkey primary key (store_id, record_time, event_number),

    constraint votes_store_results_id_fkey foreign key (store_id) references store_descriptors(id)
);

-- Index for returning paginated API responses for the UI (sorted by vote effective date).
-- The table has one row per closed vote request, so it stays small (thousands of rows).
-- Lookups by row_id and filters on the other columns scan it, no further indexes are needed.
create index votes_store_sid_effat_rt_en
    on votes_store_results (store_id, coalesce(vote_effective_at, vote_completed_at) desc, record_time desc, event_number desc);
